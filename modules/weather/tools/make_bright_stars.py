#!/usr/bin/env python3
# Builds modules/weath../bright_stars_data.h from the Yale Bright Star Catalogue, 5th revised edition
# (Hoffleit and Warren 1991; public domain): http://tdc-www.harvard.edu/catalogs/bsc5.dat.gz
#   python3 make_bright_stars.py bsc5.dat.gz ../bright_stars_data.h
# Per star: J2000 right ascension and declination, visual magnitude, B-V colour index.
import gzip
import math
import sys


def field(line, a, b):
    s = line[a - 1 : b].strip()
    return s


def main():
    src, dst = sys.argv[1], sys.argv[2]
    stars = []
    with gzip.open(src, "rt", encoding="latin-1") as f:
        for line in f:
            line = line.rstrip("\n").ljust(197)
            if not field(line, 76, 77) or not field(line, 103, 107):
                continue  # the few entries with no position or magnitude (novae, merged stars)
            ra = (int(field(line, 76, 77)) + int(field(line, 78, 79)) / 60.0 + float(field(line, 80, 83)) / 3600.0) * 15.0
            dec = int(field(line, 85, 86)) + int(field(line, 87, 88)) / 60.0 + int(field(line, 89, 90)) / 3600.0
            if field(line, 84, 84) == "-":
                dec = -dec
            vmag = float(field(line, 103, 107))
            bv = field(line, 110, 114)
            bv = float(bv) if bv else 0.6
            stars.append((ra, dec, vmag, bv))
    stars.sort(key=lambda s: s[2])
    with open(dst, "w") as o:
        o.write("// Generated by modules/weather/tools/make_bright_stars.py from the Yale Bright Star Catalogue, 5th revised\n")
        o.write("// edition (Hoffleit and Warren 1991; public domain). Do not edit.\n")
        o.write("// Each star: J2000 right ascension (65536 = 360 deg), declination (32767 = 90 deg), V magnitude x 100,\n")
        o.write("// B-V x 1000. Brightest first.\n\n#pragma once\n\n#include <cstdint>\n\n")
        o.write("static const int BRIGHT_STAR_COUNT = %d;\n" % len(stars))
        o.write("static const int16_t BRIGHT_STARS[%d * 4] = {\n" % len(stars))
        row = []
        for ra, dec, vmag, bv in stars:
            r = int(round(ra / 360.0 * 65536.0)) % 65536
            if r >= 32768:
                r -= 65536  # stored signed; read back as uint16
            row.append("%d,%d,%d,%d" % (r, int(round(dec / 90.0 * 32767.0)), int(round(vmag * 100.0)), int(round(bv * 1000.0))))
            if len(row) == 8:
                o.write("\t" + ", ".join(row) + ",\n")
                row = []
        if row:
            o.write("\t" + ", ".join(row) + ",\n")
        o.write("};\n")
    print("%d stars, brightest V %.2f, faintest %.2f" % (len(stars), stars[0][2], stars[-1][2]))


main()
